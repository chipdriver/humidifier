static int32_t HumidifierSymbolFont_FindGlyph(uint32_t unicode)
{
  for (uint32_t i = 0U; i < (sizeof(s_humidifier_symbol_glyphs) / sizeof(s_humidifier_symbol_glyphs[0])); i++)
  {
    if (s_humidifier_symbol_glyphs[i].unicode == unicode)
    {
      return (int32_t)i;
    }
  }

  return -1;
}

uint8_t HumidifierSymbolFont_HasGlyph(uint32_t unicode)
{
  return (HumidifierSymbolFont_FindGlyph(unicode) >= 0) ? 1U : 0U;
}

static bool HumidifierSymbolFont_GetGlyphDsc(const lv_font_t *font,
                                             lv_font_glyph_dsc_t *dsc_out,
                                             uint32_t letter,
                                             uint32_t letter_next)
{
  (void)font;
  (void)letter_next;

  if (dsc_out == (lv_font_glyph_dsc_t *)0)
  {
    return false;
  }

  int32_t glyph_index = HumidifierSymbolFont_FindGlyph(letter);
  if (glyph_index < 0)
  {
    return false;
  }

  dsc_out->adv_w = HUMIDIFIER_SYMBOL_ADVANCE;
  dsc_out->box_w = HUMIDIFIER_SYMBOL_SIZE;
  dsc_out->box_h = HUMIDIFIER_SYMBOL_SIZE;
  dsc_out->ofs_x = 0;
  dsc_out->ofs_y = -2;
  dsc_out->stride = HUMIDIFIER_SYMBOL_SIZE;
  dsc_out->format = LV_FONT_GLYPH_FORMAT_A8;
  dsc_out->is_placeholder = 0;
  dsc_out->req_raw_bitmap = 0;
  dsc_out->outline_stroke_width = 0;
  dsc_out->gid.index = (uint32_t)glyph_index + 1U;
  dsc_out->entry = (lv_cache_entry_t *)0;

  return true;
}

static const void *HumidifierSymbolFont_GetGlyphBitmap(lv_font_glyph_dsc_t *g_dsc, lv_draw_buf_t *draw_buf)
{
  if ((g_dsc == (lv_font_glyph_dsc_t *)0) ||
      (g_dsc->gid.index == 0U) ||
      (g_dsc->gid.index > (sizeof(s_humidifier_symbol_glyphs) / sizeof(s_humidifier_symbol_glyphs[0]))))
  {
    return (const void *)0;
  }

  const uint8_t *bitmap = s_humidifier_symbol_glyphs[g_dsc->gid.index - 1U].bitmap;
  if ((draw_buf == (lv_draw_buf_t *)0) || (draw_buf->data == (uint8_t *)0))
  {
    return bitmap;
  }

  uint32_t stride = draw_buf->header.stride;
  if (stride == 0U)
  {
    stride = HUMIDIFIER_SYMBOL_SIZE;
  }

  for (uint8_t y = 0U; y < HUMIDIFIER_SYMBOL_SIZE; y++)
  {
    for (uint32_t x = 0U; x < stride; x++)
    {
      draw_buf->data[((uint32_t)y * stride) + x] = 0x00U;
    }

    for (uint8_t x = 0U; x < HUMIDIFIER_SYMBOL_SIZE; x++)
    {
      draw_buf->data[((uint32_t)y * stride) + x] = bitmap[((uint32_t)y * HUMIDIFIER_SYMBOL_SIZE) + x];
    }
  }

  return draw_buf->data;
}

